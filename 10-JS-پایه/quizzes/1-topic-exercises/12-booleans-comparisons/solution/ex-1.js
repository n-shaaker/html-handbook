// تمرین ۱ — اول حدس، بعد اجرا

// حدس من: false
console.log('"5" === 5 :', "5" === 5);
// حدس من: true
console.log('"5" == 5 :', "5" == 5);
// حدس من: true (رشته‌ها حرف به حرف مقایسه می‌شوند)
console.log('"10" < "9" :', "10" < "9");
// حدس من: false
console.log("10 < 9 :", 10 < 9);
// حدس من: true (رشته غیرخالی truthy است)
console.log('Boolean("0") :', Boolean("0"));
// حدس من: true (رشته خالی falsy است)
console.log('!"" :', !"");
// حدس من: false (حروف بزرگ و کوچک فرق دارند)
console.log('"apple" === "Apple" :', "apple" === "Apple");
