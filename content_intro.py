def session_schedule_rows():
    rows = []
    for s in SESSIONS:
        rows.append([
            f"جلسه {s['num']}",
            s["title"],
            "۹۰ دقیقه",
            s["topics"][:60] + ("…" if len(s["topics"]) > 60 else ""),
            s["project"][:50] + ("…" if len(s["project"]) > 50 else ""),
        ])
    return rows


